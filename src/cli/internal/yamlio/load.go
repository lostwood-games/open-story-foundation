// LoadDir reads every .yaml and .json file under dir as one OSF resource. It
// checks the structure that schema/osf-v1.schema.json describes, plus
// duplicate keys; everything else (names, texts, ids, references) is left to
// check.Project so YAML and .osf projects get the same diagnostics. JSON is
// read by the YAML parser, since JSON is YAML.
func LoadDir(dir string) (*osf.Project, []diag.Diagnostic) {
	files, err := FindFiles(dir)
	if err != nil {
		return nil, []diag.Diagnostic{diag.ReadError.At(diag.Pos{}, diag.Pos{}, "%v", err)}
	}
	if len(files) == 0 {
		return nil, []diag.Diagnostic{diag.NoProject.At(diag.Pos{File: dir}, diag.Pos{}, "no .yaml or .json files found")}
	}
	l := newLoader()
	for _, path := range files {
		src, err := os.ReadFile(path)
		if err != nil {
			l.diags = append(l.diags, diag.ReadError.At(diag.Pos{File: path}, diag.Pos{}, "%v", err))
			continue
		}
		rel, _ := filepath.Rel(dir, path)
		l.file, l.rel = path, filepath.ToSlash(rel)
		l.load(src, false)
	}
	return l.p, l.diags
}

// FindFiles returns the .yaml and .json files under dir, sorted.
func FindFiles(dir string) ([]string, error) {
	yamls, err := source.Files(dir, ".yaml")
	if err != nil {
		return nil, err
	}
	jsons, err := source.Files(dir, ".json")
	if err != nil {
		return nil, err
	}
	files := append(yamls, jsons...)
	sort.Strings(files)
	return files, nil
}

// LoadFile reads one file on its own, for conversion: it may hold several
// documents separated by ---, or a JSON array, each item one resource.
// display is the path shown in messages.
func LoadFile(display string, src []byte) (*osf.Project, []diag.Diagnostic) {
	l := newLoader()
	l.file, l.rel = display, filepath.Base(display)
	l.load(src, true)
	return l.p, l.diags
}

func newLoader() *loader {
	return &loader{p: &osf.Project{APIVersions: map[string]string{}, PluginComments: map[string]osf.Comments{}}, keys: map[*yaml.Node]entry{}}
}

var generatedFrom = regexp.MustCompile(`^# Generated by osf convert(?: from (.+))?\. Do not edit\.\s*$`)

// GeneratedFrom returns the source file named in the head comment osf convert
// writes, or "" when src has no such comment (JSON has none).
func GeneratedFrom(src []byte) string {
	first, _, _ := strings.Cut(strings.TrimPrefix(string(src), "\uFEFF"), "\n")
	if m := generatedFrom.FindStringSubmatch(first); m != nil {
		return m[1]
	}
	return ""
}

type loader struct {
	p         *osf.Project
	diags     []diag.Diagnostic
	file, rel string
	// entries records, for every mapping value seen, its key and the entry
	// before it, so comments can be read back (see comments).
	keys map[*yaml.Node]entry
}

type entry struct{ key, prevKey, prevValue *yaml.Node }

// comments returns the comments written around the entry whose value is v.
func (l *loader) comments(v *yaml.Node) osf.Comments {
	e, ok := l.keys[v]
	if !ok {
		return osf.Comments{}
	}
	return comments(e.prevKey, e.prevValue, e.key, v)
}

// blockComments returns the comments of a resource block: the document's
// head comment stands apart from it, whatever is above apiVersion, kind, data
// and id is directly above it, and a comment after data: (or after one of
// the given values) trails its header line.
func (l *loader) blockComments(docHead string, root *yaml.Node, f, d map[string]*yaml.Node, trailFrom ...string) osf.Comments {
	var c osf.Comments
	if apart := osfComment(docHead); len(apart) > 0 {
		c.Head = append(apart, "")
	}
	c.Head = append(c.Head, osfComment(root.HeadComment)...)
	for _, v := range []*yaml.Node{f["apiVersion"], f["kind"], f["data"], d["id"]} {
		if v != nil {
			c.Head = append(c.Head, l.comments(v).Head...)
		}
	}
	c.Trail = l.comments(f["data"]).Trail
	for _, name := range trailFrom {
		if v := d[name]; v != nil && c.Trail == "" {
			c.Trail = l.comments(v).Trail
		}
	}
	return c
}

func (l *loader) pos(n *yaml.Node) diag.Pos {
	return diag.Pos{File: l.file, Line: n.Line, Col: n.Column}
}

// end estimates where n ends: yaml.v3 records only where a node starts, so a
// one-line scalar spans its value (plus quotes) and anything else is a point.
func (l *loader) end(n *yaml.Node) diag.Pos {
	p := l.pos(n)
	if n.Kind != yaml.ScalarNode || strings.Contains(n.Value, "\n") || n.Style&(yaml.LiteralStyle|yaml.FoldedStyle) != 0 {
		return p
	}
	p.Col += utf8.RuneCountInString(n.Value)
	if n.Style&(yaml.DoubleQuotedStyle|yaml.SingleQuotedStyle) != 0 {
		p.Col += 2
	}
	return p
}

func (l *loader) errf(r diag.Rule, n *yaml.Node, format string, args ...any) {
	p, e := diag.Pos{File: l.file}, diag.Pos{}
	if n != nil {
		p, e = l.pos(n), l.end(n)
	}
	l.diags = append(l.diags, r.At(p, e, format, args...))
}

var yamlLine = regexp.MustCompile(`^yaml: line (\d+): (.*)$`)

// load reads the resources in src. A project file holds exactly one; with
// multi set, a stream of documents or a sequence of resources is accepted.
func (l *loader) load(src []byte, multi bool) {
	dec := yaml.NewDecoder(strings.NewReader(string(src)))
	// In a stream, yaml.v3 hangs a comment that follows --- and stands apart
	// from the next document on the previous document as its foot comment.
	foot := ""
	for n := 0; ; n++ {
		var doc yaml.Node
		if err := dec.Decode(&doc); err != nil {
			if !errors.Is(err, io.EOF) {
				if m := yamlLine.FindStringSubmatch(err.Error()); m != nil {
					line, _ := strconv.Atoi(m[1])
					l.diags = append(l.diags, diag.YAMLSyntax.At(diag.Pos{File: l.file, Line: line}, diag.Pos{}, "%s", m[2]))
				} else {
					l.errf(diag.YAMLSyntax, nil, "%s", strings.TrimPrefix(err.Error(), "yaml: "))
				}
			} else if n == 0 {
				l.errf(diag.EmptyFile, nil, "file is empty; it must hold one resource")
			}
			return
		}
		if n == 1 && !multi {
			l.errf(diag.MultipleDocuments, &doc, "a file holds one resource; split the other documents into their own files")
			return
		}
		root := doc.Content[0]
		head := strings.TrimSpace(foot + "\n" + doc.HeadComment)
		foot = doc.FootComment
		if multi && root.Kind == yaml.SequenceNode {
			for _, item := range root.Content {
				l.resource(item, "")
			}
			continue
		}
		l.resource(root, head)
	}
}

// fields checks that n is a mapping with no repeated, unknown or missing keys
// and returns its values by key.
func (l *loader) fields(n *yaml.Node, what string, sh shape) map[string]*yaml.Node {
	allowed, required := sh.allowed, sh.required
	if n.Kind != yaml.MappingNode {
		l.errf(diag.WrongType, n, "%s must be a mapping", what)
		return nil
	}
	out := l.entries(n, what, diag.DuplicateField)
	for k, v := range out {
		if !contains(allowed, k) {
			l.errf(diag.UnknownField, keyNode(n, v), "%s: unknown field %q; expected %s", what, k, strings.Join(allowed, ", "))
			delete(out, k)
		}
	}
	for _, k := range required {
		if out[k] == nil {
			l.errf(diag.MissingField, n, "%s: missing required field %q", what, k)
		}
	}
	return out
}

// entries returns the values of mapping n by key, reporting repeated keys
// with rule dup, since YAML parsers otherwise silently overwrite them.
func (l *loader) entries(n *yaml.Node, what string, dup diag.Rule) map[string]*yaml.Node {
	out := map[string]*yaml.Node{}
	for i := 0; i+1 < len(n.Content); i += 2 {
		k := n.Content[i]
		if prev, seen := out[k.Value]; seen {
			l.errf(dup, k, "%s: key %q is repeated (first on line %d)", what, k.Value, keyNode(n, prev).Line)
			continue
		}
		out[k.Value] = n.Content[i+1]
		e := entry{key: k}
		if i > 0 {
			e.prevKey, e.prevValue = n.Content[i-2], n.Content[i-1]
		}
		l.keys[n.Content[i+1]] = e
	}
	return out
}

// ordered returns the keys and values of mapping n in file order, repeated
// keys dropped.
func ordered(n *yaml.Node) (keys []*yaml.Node, values []*yaml.Node) {
	seen := map[string]bool{}
	for i := 0; i+1 < len(n.Content); i += 2 {
		if seen[n.Content[i].Value] {
			continue
		}
		seen[n.Content[i].Value] = true
		keys = append(keys, n.Content[i])
		values = append(values, n.Content[i+1])
	}
	return
}

func keyNode(m, v *yaml.Node) *yaml.Node {
	for i := 1; i < len(m.Content); i += 2 {
		if m.Content[i] == v {
			return m.Content[i-1]
		}
	}
	return v
}

func (l *loader) str(n *yaml.Node, what string) (string, bool) {
	if n == nil {
		return "", false
	}
	if n.Kind != yaml.ScalarNode || n.ShortTag() != "!!str" {
		l.errf(diag.WrongType, n, "%s must be a string", what)
		return "", false
	}
	return n.Value, true
}

func (l *loader) text(n *yaml.Node, what string) *osf.Str {
	if n == nil || n.ShortTag() == "!!null" {
		return nil
	}
	s, ok := l.str(n, what)
	if !ok {
		return nil
	}
	return &osf.Str{Value: s, Pos: l.pos(n), End: l.end(n), Comments: l.comments(n)}
}

func (l *loader) matching(n *yaml.Node, what string, re *regexp.Regexp, rule string) *osf.Str {
	s := l.text(n, what)
	if s != nil && !re.MatchString(s.Value) {
		l.errf(diag.BadReference, n, "%s %q %s", what, s.Value, rule)
		return nil
	}
	return s
}

// id returns a resource id; the checker validates it.
func (l *loader) id(n *yaml.Node, what string) string {
	s, _ := l.str(n, what)
	return s
}

// idPos is where the characters of a scalar id start: after the opening
// quote when it has one, so that osf.IDSpan covers exactly the id.
func (l *loader) idPos(n *yaml.Node) diag.Pos {
	if n == nil {
		return diag.Pos{}
	}
	p := l.pos(n)
	if n.Style&(yaml.DoubleQuotedStyle|yaml.SingleQuotedStyle) != 0 {
		p.Col++
	}
	return p
}

// keyIDs returns the resource ids a translation key names, placed inside
// the key scalar: the segment after Story, Character, Document or Dialogue, and the
// segments after nodes and options.
func (l *loader) keyIDs(k *yaml.Node) []osf.Str {
	var ids []osf.Str
	parts := strings.Split(k.Value, ".")
	col := l.idPos(k).Col
	for i, part := range parts {
		if i > 0 && (i == 1 || parts[i-1] == "nodes" || parts[i-1] == "options") {
			ids = append(ids, osf.IDSpan(part, diag.Pos{File: l.file, Line: k.Line, Col: col}))
		}
		col += len(part) + 1 // keys match keyPattern: ASCII, one column per byte
	}
	return ids
}

func (l *loader) value(n *yaml.Node, what string) (osf.Value, bool) {
	if n.Kind == yaml.ScalarNode {
		switch n.ShortTag() {
		case "!!bool":
			return osf.Value{Kind: osf.Bool, Bool: n.Value == "true"}, true
		case "!!int":
			if i, err := strconv.ParseInt(n.Value, 0, 64); err == nil && i >= osf.MinNumber && i <= osf.MaxNumber {
				return osf.Value{Kind: osf.Int, Int: i}, true
			}
			l.errf(diag.NumberTooLarge, n, "number %s is too large", n.Value)
			return osf.Value{}, false
		}
	}
	l.errf(diag.WrongType, n, "%s must be a boolean or a whole number", what)
	return osf.Value{}, false
}

// assign reads one entry of a set or requires map: a plain value, or a
// mapping of opKey (operation or operator) and value.
func (l *loader) assign(n *yaml.Node, what, opKey string, ops []osf.Op) (osf.Op, osf.Value, bool) {
	if n.Kind != yaml.MappingNode {
		v, ok := l.value(n, what)
		return "", v, ok
	}
	f := l.fields(n, what, shapes[map[string]string{"operation": "SetOperation", "operator": "Condition"}[opKey]])
	if f[opKey] == nil || f["value"] == nil {
		return "", osf.Value{}, false
	}
	name, _ := l.str(f[opKey], what+"."+opKey)
	var op osf.Op
	for _, o := range ops {
		if string(o) == name {
			op = o
		}
	}
	if op == "" {
		names := make([]string, len(ops))
		for i, o := range ops {
			names[i] = string(o)
		}
		l.errf(diag.WrongType, f[opKey], "%s.%s must be one of %s", what, opKey, strings.Join(names, ", "))
		return "", osf.Value{}, false
	}
	v, ok := l.value(f["value"], what+".value")
	return op, v, ok
}

func (l *loader) values(n *yaml.Node, what string) ([]osf.Assign, osf.Comments) {
	opKey, ops := "operation", osf.SetOps
	if strings.HasSuffix(what, ".requires") {
		opKey, ops = "operator", osf.CompareOps
	}
	if n == nil {
		return nil, osf.Comments{}
	}
	if n.Kind != yaml.MappingNode {
		l.errf(diag.WrongType, n, "%s must be a mapping of variable to value", what)
		return nil, osf.Comments{}
	}
	l.entries(n, what, diag.DuplicateField)
	var out []osf.Assign
	keys, vals := ordered(n)
	for i, k := range keys {
		if op, v, ok := l.assign(vals[i], what+"."+k.Value, opKey, ops); ok {
			out = append(out, osf.Assign{Name: k.Value, Op: op, Value: v, Pos: l.pos(k), End: l.end(k)})
		}
	}
	return out, l.comments(n)
}

// requires reads the conditions of an option or a branch. The short form is a
// mapping of variable to value, all of which must be met. The full form names
// the logic: `all` is a list of { variable, operator, value } that must all be
// met, and `any` is a list of such `all` groups of which one is enough. The
// groups after the first are returned as or.
func (l *loader) requires(n *yaml.Node, what string) (first []osf.Assign, or [][]osf.Assign, c osf.Comments) {
	if n == nil {
		return nil, nil, osf.Comments{}
	}
	if !isConditions(n) {
		first, c = l.values(n, what)
		return first, nil, c
	}
	f := l.fields(n, what, shapes["Conditions"])
	c = l.comments(n)
	switch any, all := f["any"], f["all"]; {
	case any != nil && all != nil:
		l.errf(diag.WrongType, n, "%s takes any or all, not both; put the all group inside any", what)
	case all != nil:
		first = l.conditionGroup(all, what+".all")
	case any != nil:
		if len(any.Content) == 0 {
			l.errf(diag.WrongType, any, "%s.any must be a non-empty list of { all: [...] } groups", what)
		}
		for i, item := range any.Content {
			iw := what + ".any[" + strconv.Itoa(i) + "]"
			g := l.fields(item, iw, shapes["ConditionGroup"])
			if g == nil || g["all"] == nil {
				continue
			}
			group := l.conditionGroup(g["all"], iw+".all")
			if len(group) == 0 {
				continue
			}
			if first == nil {
				first = group
			} else {
				or = append(or, group)
			}
		}
	}
	return first, or, c
}

// isConditions reports whether a requires mapping is the full form: it has
// an `any` or `all` key holding a list. A variable named any or all in the
// short form holds a value or a mapping, never a list.
func isConditions(n *yaml.Node) bool {
	if n.Kind != yaml.MappingNode {
		return false
	}
	for i := 0; i+1 < len(n.Content); i += 2 {
		if k := n.Content[i].Value; (k == "any" || k == "all") && n.Content[i+1].Kind == yaml.SequenceNode {
			return true
		}
	}
	return false
}

// conditionGroup reads the list under `all`: conditions written as
// { variable, operator, value }, where operator is == or a comparison.
func (l *loader) conditionGroup(n *yaml.Node, what string) []osf.Assign {
	if n.Kind != yaml.SequenceNode || len(n.Content) == 0 {
		l.errf(diag.WrongType, n, "%s must be a non-empty list of { variable, operator, value }", what)
		return nil
	}
	var out []osf.Assign
	seen := map[string]bool{}
	for i, item := range n.Content {
		iw := what + "[" + strconv.Itoa(i) + "]"
		f := l.fields(item, iw, shapes["VariableCondition"])
		if f == nil || f["variable"] == nil || f["operator"] == nil || f["value"] == nil {
			continue
		}
		name, ok := l.str(f["variable"], iw+".variable")
		if !ok {
			continue
		}
		opName, _ := l.str(f["operator"], iw+".operator")
		op, known := osf.OpEqual, opName == "=="
		for _, o := range osf.CompareOps {
			if string(o) == opName {
				op, known = o, true
			}
		}
		if !known {
			l.errf(diag.WrongType, f["operator"], "%s.operator must be one of ==, !=, <, <=, >, >=", iw)
			continue
		}
		v, ok := l.value(f["value"], iw+".value")
		if !ok {
			continue
		}
		a := osf.Assign{Name: name, Op: op, Value: v, Pos: l.pos(f["variable"]), End: l.end(f["variable"])}
		if cond := a.RequiresString(); seen[cond] {
			l.errf(diag.DuplicateField, item, "%s: %s is already required", what, cond)
			continue
		} else {
			seen[cond] = true
		}
		out = append(out, a)
	}
	return out
}

// resource reads one resource; docHead is the head comment of its document.
func (l *loader) resource(root *yaml.Node, docHead string) {
	f := l.fields(root, "resource", shapes["resource"])
	if f == nil || f["apiVersion"] == nil || f["kind"] == nil || f["data"] == nil {
		return
	}
	block := func(d map[string]*yaml.Node, trailFrom ...string) osf.Comments {
		return l.blockComments(docHead, root, f, d, trailFrom...)
	}
	api, _ := l.str(f["apiVersion"], "apiVersion")
	kind, _ := l.str(f["kind"], "kind")
	data := f["data"]
	plugin, version, _ := strings.Cut(api, "/")
	pos, end := l.pos(root), l.end(f["kind"])
	switch api + " " + kind {
	case "story/v1 Story":
		d := l.fields(data, "Story", shapes["Story"])
		if d == nil {
			return
		}
		l.p.Stories = append(l.p.Stories, &osf.Story{
			ID: l.id(d["id"], "id"), Name: l.text(d["name"], "name"), Description: l.text(d["description"], "description"),
			Start: l.matching(d["start"], "start", dialogueRef, "must be Dialogue.<id>"), Pos: pos, End: end, IDPos: l.idPos(d["id"]), File: l.rel,
			Comments: block(d, "id"),
		})
	case "story/v1 Character":
		d := l.fields(data, "Character", shapes["Character"])
		if d == nil {
			return
		}
		l.p.Characters = append(l.p.Characters, &osf.Character{
			ID: l.id(d["id"], "id"), Name: l.text(d["name"], "name"), Description: l.text(d["description"], "description"),
			Pos: pos, End: end, IDPos: l.idPos(d["id"]), File: l.rel,
			Comments: block(d, "id"),
		})
	case "story/v1 Document":
		d := l.fields(data, "Document", shapes["Document"])
		if d == nil {
			return
		}
		l.p.Documents = append(l.p.Documents, &osf.Document{
			ID: l.id(d["id"], "id"), Name: l.text(d["name"], "name"),
			Pos: pos, End: end, IDPos: l.idPos(d["id"]), File: l.rel,
			Comments: block(d, "id"),
		})
	case "story/v1 Variable":
		d := l.fields(data, "Variable", shapes["Variable"])
		if d == nil || d["type"] == nil || d["default"] == nil {
			return
		}
		v := &osf.Variable{ID: l.id(d["id"], "id"), Pos: pos, End: end, IDPos: l.idPos(d["id"]), File: l.rel, Comments: block(d, "id", "default")}
		switch t, _ := l.str(d["type"], "type"); t {
		case "boolean":
			v.Type = osf.Boolean
		case "number":
			v.Type = osf.Number
		case "unsignedNumber":
			v.Type = osf.UnsignedNumber
		default:
			l.errf(diag.UnknownVariableType, d["type"], "unknown variable type %q; expected boolean, number or unsignedNumber", t)
			return
		}
		v.Description = l.text(d["description"], "description")
		var ok bool
		if v.Default, ok = l.value(d["default"], "default"); ok {
			l.p.Variables = append(l.p.Variables, v)
		}
	case "dialogue/v1 Dialogue":
		l.dialogue(data, pos, end, block)
	case "i18n/v1 Locale":
		d := l.fields(data, "Locale", shapes["Locale"])
		if d == nil || d["values"] == nil {
			return
		}
		loc := &osf.Locale{Pos: pos, End: end, File: l.rel, Comments: block(d)}
		if s := l.text(d["language"], "language"); s != nil {
			loc.Language = *s
		}
		if d["values"].Kind != yaml.MappingNode {
			l.errf(diag.WrongType, d["values"], "values must be a mapping of translation key to text")
			return
		}
		l.entries(d["values"], "values", diag.DuplicateTranslation)
		keys, vals := ordered(d["values"])
		for i, k := range keys {
			if !keyPattern.MatchString(k.Value) {
				l.errf(diag.BadTranslationKey, k, "%q is not a translation key like Dialogue.<id>.nodes.<node>.content.text", k.Value)
				continue
			}
			if s := l.text(vals[i], k.Value); s != nil {
				loc.Values = append(loc.Values, osf.LocaleValue{Key: k.Value, Text: *s, IDs: l.keyIDs(k)})
			}
		}
		l.p.Locales = append(l.p.Locales, loc)
	case "i18n/v1 Configuration":
		d := l.fields(data, "i18n Configuration", shapes["I18nConfiguration"])
		if d == nil || d["locales"] == nil {
			return
		}
		c := &osf.I18n{Source: l.text(d["source"], "source"), Pos: pos, End: end, File: l.rel, Comments: block(d)}
		if d["locales"].Kind != yaml.MappingNode {
			l.errf(diag.WrongType, d["locales"], "locales must be a mapping of name to { id, enforce }")
			return
		}
		l.entries(d["locales"], "locales", diag.DuplicateField)
		keys, vals := ordered(d["locales"])
		for i, k := range keys {
			lf := l.fields(vals[i], "locales."+k.Value, shapes["I18nLocale"])
			if lf == nil {
				continue
			}
			def := osf.LocaleDef{Name: k.Value, Pos: l.pos(k), End: l.end(k), Comments: l.comments(vals[i])}
			if lf["id"] != nil {
				def.ID, _ = l.str(lf["id"], "id")
				def.Pos, def.End = l.pos(lf["id"]), l.end(lf["id"])
			}
			if e := lf["enforce"]; e != nil {
				if e.ShortTag() != "!!bool" {
					l.errf(diag.ExpectedValue, e, "enforce must be true or false")
				}
				def.Enforce = e.Value == "true"
			}
			c.Locales = append(c.Locales, def)
		}
		l.p.I18n = append(l.p.I18n, c)
	case "plugins/v1 Configuration":
		d := l.fields(data, "plugins Configuration", shapes["PluginsConfiguration"])
		if d == nil || d["plugins"] == nil {
			return
		}
		if l.p.PluginsSet {
			l.errf(diag.DuplicateVersions, root, "a project has one plugins/v1 Configuration; the first is at %s", l.p.PluginsPos)
		}
		l.p.PluginsSet, l.p.PluginsPos, l.p.PluginsComments = true, pos, block(d)
		if d["plugins"].Kind != yaml.SequenceNode {
			l.errf(diag.WrongType, d["plugins"], "plugins must be a list such as [i18n/v1]")
			return
		}
		for _, item := range d["plugins"].Content {
			if s := l.matching(item, "plugin", pluginPatt, "must look like name/v1"); s != nil {
				if contains(l.p.Plugins, s.Value) {
					l.errf(diag.DuplicatePlugin, item, "plugin %s is listed twice", s.Value)
					continue
				}
				name, version, _ := strings.Cut(s.Value, "/")
				if versions, known := osf.Supported[name]; !known || name == "language" {
					l.errf(diag.UnknownPlugin, item, "unknown plugin %q; this version of osf knows story/v1, dialogue/v1 and i18n/v1", s.Value)
					continue
				} else if !contains(versions, version) {
					l.errf(diag.UnsupportedVersion, item, "plugin %s is not supported by this version of osf (supported: %s/%s)", s.Value, name, strings.Join(versions, ", "+name+"/"))
					continue
				}
				l.p.Plugins = append(l.p.Plugins, s.Value)
				l.p.PluginComments[s.Value] = osf.Comments{Head: osfComment(item.HeadComment), Trail: osfLine(item.LineComment)}
			}
		}
	default:
		switch plugin {
		case "story", "dialogue", "i18n", "plugins":
			if version != "v1" {
				l.errf(diag.UnsupportedVersion, f["apiVersion"], "apiVersion %s is not supported by this version of osf (supported: %s/v1)", api, plugin)
			} else {
				l.errf(diag.UnknownKind, f["kind"], "kind %q is not part of %s", kind, api)
			}
		default:
			l.errf(diag.UnknownPlugin, f["apiVersion"], "unknown apiVersion %q; expected story/v1, dialogue/v1, i18n/v1 or plugins/v1", api)
		}
		return
	}
	l.p.APIVersions[plugin] = version
}

func (l *loader) dialogue(data *yaml.Node, pos, end diag.Pos, block func(map[string]*yaml.Node, ...string) osf.Comments) {
	d := l.fields(data, "Dialogue", shapes["Dialogue"])
	if d == nil {
		return
	}
	dlg := &osf.Dialogue{ID: l.id(d["id"], "id"), Name: l.text(d["name"], "name"), Pos: pos, End: end, IDPos: l.idPos(d["id"]), File: l.rel, Comments: block(d, "id")}
	if s := l.text(d["startNode"], "startNode"); s != nil {
		dlg.StartNode = s
	}
	next := func(n *yaml.Node, where string) (*osf.Str, []*osf.Branch) {
		return l.nexts(n, where+".next")
	}
	if nodes := d["nodes"]; nodes != nil {
		if nodes.Kind != yaml.MappingNode {
			l.errf(diag.WrongType, nodes, "nodes must be a mapping of node id to node")
		} else {
			l.entries(nodes, "nodes", diag.DuplicateNode)
			keys, vals := ordered(nodes)
			for i, k := range keys {
				where := "nodes." + k.Value
				nf := l.fields(vals[i], where, shapes["Node"])
				if nf == nil {
					continue
				}
				n := &osf.Node{ID: k.Value, Pos: l.pos(k), End: l.end(k), IDPos: l.idPos(k), Comments: l.comments(vals[i])}
				n.Next, n.Branches = next(nf["next"], where)
				n.Set, n.SetComments = l.values(nf["set"], where+".set")
				if c := nf["content"]; c != nil {
					cf := l.fields(c, where+".content", shapes["Content"])
					n.Speaker = l.matching(cf["speaker"], "speaker", characterRef, "must be Character.<id>")
					n.Title = l.text(cf["title"], "title")
					n.Text = l.text(cf["text"], "text")
				}
				if opts := nf["options"]; opts != nil {
					if opts.Kind != yaml.MappingNode || len(opts.Content) == 0 {
						l.errf(diag.WrongType, opts, "%s.options must be a non-empty mapping of option id to option", where)
					} else {
						l.entries(opts, where+".options", diag.DuplicateOption)
						okeys, ovals := ordered(opts)
						for j, okey := range okeys {
							ow := where + ".options." + okey.Value
							of := l.fields(ovals[j], ow, shapes["Option"])
							if of == nil {
								continue
							}
							o := &osf.Option{ID: okey.Value, Pos: l.pos(okey), End: l.end(okey), IDPos: l.idPos(okey), Comments: l.comments(ovals[j])}
							o.Next, o.Branches = next(of["next"], ow)
							o.Requires, o.RequiresOr, o.RequiresComments = l.requires(of["requires"], ow+".requires")
							o.Set, o.SetComments = l.values(of["set"], ow+".set")
							if c := of["content"]; c != nil {
								cf := l.fields(c, ow+".content", shapes["OptionContent"])
								o.Text = l.text(cf["text"], "text")
							}
							n.Options = append(n.Options, o)
						}
					}
				}
				dlg.Nodes = append(dlg.Nodes, n)
			}
		}
	}
	l.p.Dialogues = append(l.p.Dialogues, dlg)
}

// nexts reads `next`: a node id or Dialogue.<id>, or a list of branches
// `{ to, requires }` tried in order, of which only the last may leave out
// requires. That last one is returned as the plain next.
func (l *loader) nexts(n *yaml.Node, what string) (*osf.Str, []*osf.Branch) {
	target := func(n *yaml.Node, what string) *osf.Str {
		return l.matching(n, what, nextPattern, "must be a node id or Dialogue.<id>")
	}
	if n == nil {
		return nil, nil
	}
	if n.Kind != yaml.SequenceNode {
		return target(n, "next"), nil
	}
	if len(n.Content) == 0 {
		l.errf(diag.WrongType, n, "%s must be a node id, Dialogue.<id> or a non-empty list of { to, requires }", what)
		return nil, nil
	}
	var next *osf.Str
	var branches []*osf.Branch
	for i, item := range n.Content {
		iw := what + "[" + strconv.Itoa(i) + "]"
		f := l.fields(item, iw, shapes["Branch"])
		if f == nil || f["to"] == nil {
			continue
		}
		head := item.HeadComment
		if len(item.Content) > 0 && item.Content[0].HeadComment != "" {
			head = item.Content[0].HeadComment
		}
		c := osf.Comments{Head: osfComment(head), Trail: osfLine(f["to"].LineComment)}
		to := target(f["to"], iw+".to")
		if to == nil {
			continue
		}
		requires, or, _ := l.requires(f["requires"], iw+".requires")
		if len(requires) == 0 {
			if i != len(n.Content)-1 {
				l.errf(diag.BranchAfterFallback, item, "%s has no requires, so the branches after it are never taken; move it to the end of the list", iw)
				continue
			}
			to.Comments = c
			next = to
			continue
		}
		branches = append(branches, &osf.Branch{To: to, Requires: requires, RequiresOr: or, Comments: c})
	}
	return next, branches
}

func contains(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}
