// Package yamlio reads and writes Open Story YAML and JSON resources
// (docs/spec.md).
package yamlio

import (
	"bytes"
	"fmt"
	"path"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/lostwood-games/open-story-foundation/src/cli/internal/osf"
)

// File is one rendered resource file. Path is relative to the output folder,
// with / separators; Source is the project file the resource came from.
type File struct {
	Path    string
	Source  string
	Content []byte
}

// Resource is one OSF resource ready to be encoded. Path has no extension.
// Comments are those of the block it came from (language.md §11.2).
type Resource struct {
	Path     string
	Source   string
	API      string
	Kind     string
	Data     *yaml.Node
	Comments osf.Comments
}

// Render turns a project into one YAML file per resource, with a head comment
// naming the source file. Each file sits next to where its source was:
// arc_1_war/01_intro_scene.osf gives arc_1_war/01_intro_scene.yaml,
// characters/characters.osf gives one file per character in characters/,
// documents/documents.osf one per document in documents/, and a Locale file keeps its own path.
func Render(p *osf.Project) ([]File, error) {
	return RenderFormat(p, "yaml")
}

// RenderFormat is Render for "yaml" or "json". JSON files carry no comment.
func RenderFormat(p *osf.Project, format string) ([]File, error) {
	resources, err := Resources(p)
	if err != nil {
		return nil, err
	}
	var files []File
	for _, r := range resources {
		comment := "Generated by osf build. Do not edit."
		if r.Source != "" {
			comment = fmt.Sprintf("Generated by osf build from %s. Do not edit.", r.Source)
		}
		content, err := Encode(r, format, comment)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", r.Path, err)
		}
		files = append(files, File{Path: r.Path + "." + format, Source: r.Source, Content: content})
	}
	return files, nil
}

// Encode writes one resource as YAML or JSON. comment, when not empty, is
// written first in the head comment in YAML; JSON carries no comment at all.
func Encode(r Resource, format, comment string) ([]byte, error) {
	root := mapping("apiVersion", str(r.API), "kind", str(r.Kind), "data", r.Data)
	switch format {
	case "yaml":
		apart, above := splitHead(r.Comments.Head)
		var head []string
		if comment != "" {
			head = append(head, "# "+comment)
		}
		if len(apart) > 0 {
			head = append(head, yamlComment(apart))
		}
		root.Content[0].HeadComment = yamlComment(above)
		root.Content[4].LineComment = lineComment(r.Comments.Trail)
		doc := &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{root}, HeadComment: strings.Join(head, "\n")}
		var buf bytes.Buffer
		enc := yaml.NewEncoder(&buf)
		enc.SetIndent(2)
		if err := enc.Encode(doc); err != nil {
			return nil, err
		}
		enc.Close()
		return buf.Bytes(), nil
	case "json":
		return EncodeJSON(root)
	}
	return nil, fmt.Errorf("unknown format %q; use yaml or json", format)
}

// Resources lists the project's resources in build order: plugins, i18n,
// Story, Characters, Documents, Variables, Dialogues, then one Locale per source file and
// language. See Render for where each one's Path points.
func Resources(p *osf.Project) ([]Resource, error) {
	r := &renderer{p: p, used: map[string]bool{}}
	if len(p.Plugins) > 0 {
		seq := &yaml.Node{Kind: yaml.SequenceNode}
		for _, pl := range p.Plugins {
			item := str(pl)
			c := p.PluginComments[pl]
			item.HeadComment = yamlComment(trimBlank(c.Head))
			item.LineComment = lineComment(c.Trail)
			seq.Content = append(seq.Content, item)
		}
		r.add("plugins/plugins", "", "plugins/v1", "Configuration", mapping("plugins", seq), p.PluginsComments)
	}
	for _, c := range p.I18n {
		locales := mapping()
		for _, l := range c.Locales {
			key, def := str(l.Name), mapping("id", str(l.ID), "enforce", boolean(l.Enforce))
			comment(key, def, l.Comments)
			locales.Content = append(locales.Content, key, def)
		}
		data := mapping()
		addText(data, "source", c.Source)
		data.Content = append(data.Content, str("locales"), locales)
		r.add("plugins/i18n", c.File, r.api("i18n"), "Configuration", data, c.Comments)
	}
	for _, s := range p.Stories {
		data := mapping("id", str(s.ID))
		addText(data, "name", s.Name)
		addText(data, "description", s.Description)
		addText(data, "start", s.Start)
		r.add(path.Join(path.Dir(s.File), "story"), s.File, r.api("story"), "Story", data, s.Comments)
	}
	for _, c := range p.Characters {
		data := mapping("id", str(c.ID))
		addText(data, "name", c.Name)
		addText(data, "description", c.Description)
		r.add(path.Join(path.Dir(c.File), c.ID), c.File, r.api("story"), "Character", data, c.Comments)
	}
	for _, d := range p.Documents {
		data := mapping("id", str(d.ID))
		addText(data, "name", d.Name)
		r.add(path.Join(path.Dir(d.File), d.ID), d.File, r.api("story"), "Document", data, d.Comments)
	}
	for _, v := range p.Variables {
		// A Variable is one line, so a comment after it sits on its value.
		dflt := value(v.Default)
		dflt.LineComment = lineComment(v.Comments.Trail)
		data := mapping("id", str(v.ID), "type", str(v.Type.String()), "default", dflt)
		r.add(path.Join(path.Dir(v.File), "variables", v.ID), v.File, r.api("story"), "Variable", data, osf.Comments{Head: v.Comments.Head})
	}
	for _, d := range p.Dialogues {
		r.add(path.Join(path.Dir(d.File), d.ID), d.File, r.api("dialogue"), "Dialogue", dialogue(d), d.Comments)
	}
	// One Locale resource per source file and language.
	type key struct{ file, lang string }
	merged := map[key]*yaml.Node{}
	heads := map[key]osf.Comments{}
	var order []key
	for _, l := range p.Locales {
		k := key{l.File, l.Language.Value}
		if merged[k] == nil {
			merged[k] = mapping()
			heads[k] = l.Comments
			order = append(order, k)
		}
		for _, v := range l.Values {
			addText(merged[k], v.Key, &v.Text)
		}
	}
	for _, k := range order {
		out := strings.TrimSuffix(k.file, path.Ext(k.file))
		r.add(out, k.file, r.api("i18n"), "Locale", mapping("language", str(k.lang), "values", merged[k]), heads[k])
	}
	return r.resources, nil
}

type renderer struct {
	p         *osf.Project
	resources []Resource
	used      map[string]bool
}

func (r *renderer) api(plugin string) string {
	v := r.p.APIVersions[plugin]
	if v == "" {
		v = "v1"
	}
	return plugin + "/" + v
}

func (r *renderer) add(out, source, api, kind string, data *yaml.Node, c osf.Comments) {
	out = path.Clean(out)
	if r.used[out] {
		base := out
		out = base + "." + strings.ToLower(kind)
		for i := 2; r.used[out]; i++ {
			out = base + "." + strings.ToLower(kind) + strconv.Itoa(i)
		}
	}
	r.used[out] = true
	r.resources = append(r.resources, Resource{Path: out, Source: source, API: api, Kind: kind, Data: data, Comments: c})
}

func dialogue(d *osf.Dialogue) *yaml.Node {
	data := mapping("id", str(d.ID))
	addText(data, "name", d.Name)
	start := ""
	if d.StartNode != nil {
		start = d.StartNode.Value
	} else if len(d.Nodes) > 0 {
		start = d.Nodes[0].ID
	}
	data.Content = append(data.Content, str("startNode"), str(start))
	nodes := mapping()
	for _, n := range d.Nodes {
		node := mapping()
		addValues(node, "set", n.Set, n.SetComments)
		addText(node, "next", n.Next)
		content := mapping()
		addText(content, "speaker", n.Speaker)
		addText(content, "title", n.Title)
		addText(content, "text", n.Text)
		node.Content = append(node.Content, str("content"), content)
		if len(n.Options) > 0 {
			options := mapping()
			for _, o := range n.Options {
				opt := mapping()
				addValues(opt, "requires", o.Requires, o.RequiresComments)
				addValues(opt, "set", o.Set, o.SetComments)
				addText(opt, "next", o.Next)
				content := mapping()
				addText(content, "text", o.Text)
				opt.Content = append(opt.Content, str("content"), content)
				key := str(o.ID)
				comment(key, opt, o.Comments)
				options.Content = append(options.Content, key, opt)
			}
			node.Content = append(node.Content, str("options"), options)
		}
		key := str(n.ID)
		comment(key, node, n.Comments)
		nodes.Content = append(nodes.Content, key, node)
	}
	data.Content = append(data.Content, str("nodes"), nodes)
	return data
}

func mapping(kv ...any) *yaml.Node {
	n := &yaml.Node{Kind: yaml.MappingNode}
	for i := 0; i < len(kv); i += 2 {
		n.Content = append(n.Content, str(kv[i].(string)), kv[i+1].(*yaml.Node))
	}
	return n
}

func str(s string) *yaml.Node {
	n := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: s}
	if strings.Contains(s, "\n") {
		n.Style = yaml.LiteralStyle
	}
	return n
}

func boolean(b bool) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!bool", Value: strconv.FormatBool(b)}
}

func value(v osf.Value) *yaml.Node {
	switch v.Kind {
	case osf.Bool:
		return boolean(v.Bool)
	}
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: strconv.FormatInt(v.Int, 10)}
}

func addText(m *yaml.Node, key string, s *osf.Str) {
	if s != nil {
		k, v := str(key), str(s.Value)
		comment(k, v, s.Comments)
		m.Content = append(m.Content, k, v)
	}
}

func addValues(m *yaml.Node, key string, values []osf.Assign, c osf.Comments) {
	if len(values) == 0 {
		return
	}
	vm := mapping()
	opKey := "operation"
	if key == "requires" {
		opKey = "operator"
	}
	for _, a := range values {
		v := value(a.Value)
		if a.Op != "" {
			v = mapping(opKey, str(string(a.Op)), "value", v)
		}
		vm.Content = append(vm.Content, str(a.Name), v)
	}
	k := str(key)
	comment(k, vm, c)
	m.Content = append(m.Content, k, vm)
}
