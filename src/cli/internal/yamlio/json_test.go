func TestEncodeJSON(t *testing.T) {
	src := "apiVersion: dialogue/v1\nkind: Dialogue\ndata:\n  id: d\n  startNode: n\n  nodes:\n    n:\n      set: {gold: 3, brave: true, name: \"<b> & \\\"q\\\"\"}\n      content:\n        text: |\n          a\n          b\n      options: {}\n  tags: []\n"
	var doc yaml.Node
	if err := yaml.Unmarshal([]byte(src), &doc); err != nil {
		t.Fatal(err)
	}
	out, err := EncodeJSON(&doc)
	if err != nil {
		t.Fatal(err)
	}
	want := `{
  "apiVersion": "dialogue/v1",
  "kind": "Dialogue",
  "data": {
    "id": "d",
    "startNode": "n",
    "nodes": {
      "n": {
        "set": {
          "gold": 3,
          "brave": true,
          "name": "<b> & \"q\""
        },
        "content": {
          "text": "a\nb\n"
        },
        "options": {}
      }
    },
    "tags": []
  }
}
`
	if string(out) != want {
		t.Errorf("got:\n%s\nwant:\n%s", out, want)
	}
	// The JSON holds the same values as the YAML.
	var fromJSON, fromYAML any
	if err := json.Unmarshal(out, &fromJSON); err != nil {
		t.Fatal(err)
	}
	if err := yaml.Unmarshal([]byte(src), &fromYAML); err != nil {
		t.Fatal(err)
	}
	fromYAML = normalise(fromYAML)
	if !reflect.DeepEqual(fromJSON, fromYAML) {
		t.Errorf("JSON %v\nYAML %v", fromJSON, fromYAML)
	}
}

// normalise makes a yaml.Unmarshal result comparable with encoding/json's.
func normalise(v any) any {
	switch x := v.(type) {
	case map[string]any:
		for k, val := range x {
			x[k] = normalise(val)
		}
		return x
	case []any:
		if len(x) == 0 {
			return []any{}
		}
		for i, val := range x {
			x[i] = normalise(val)
		}
		return x
	case int:
		return float64(x)
	}
	return v
}

func TestGeneratedFrom(t *testing.T) {
	cases := map[string]string{
		"# Generated by osf convert from arc_1_war/01_intro_scene.osf. Do not edit.\n\napiVersion: x\n": "arc_1_war/01_intro_scene.osf",
		"\uFEFF# Generated by osf convert from story.osf. Do not edit.\n":                               "story.osf",
		"# Generated by osf convert. Do not edit.\n":                                                    "",
		"# yaml-language-server: $schema=../schema/osf-v1.schema.json\napiVersion: x\n":                 "",
		"{\n  \"apiVersion\": \"story/v1\"\n}\n":                                                        "",
	}
	for src, want := range cases {
		if got := GeneratedFrom([]byte(src)); got != want {
			t.Errorf("GeneratedFrom(%q) = %q, want %q", src, got, want)
		}
	}
}

func TestLoadFileStreams(t *testing.T) {
	yamlDocs := "apiVersion: story/v1\nkind: Character\ndata: {id: a, name: A}\n---\napiVersion: story/v1\nkind: Character\ndata: {id: b, name: B}\n"
	jsonArray := `[{"apiVersion": "story/v1", "kind": "Character", "data": {"id": "a", "name": "A"}},
{"apiVersion": "story/v1", "kind": "Character", "data": {"id": "b", "name": "B"}}]`
	for _, src := range []string{yamlDocs, jsonArray} {
		p, diags := LoadFile("x", []byte(src))
		if len(diags) > 0 || len(p.Characters) != 2 || p.Characters[1].ID != "b" {
			t.Errorf("LoadFile(%q): %v, %d documents", src, diags, len(p.Characters))
		}
	}
	// Project files still hold one resource each.
	l := newLoader()
	l.load([]byte(yamlDocs), false)
	if len(l.diags) != 1 || len(l.p.Characters) != 1 {
		t.Errorf("project file with two documents: %v", l.diags)
	}
}
